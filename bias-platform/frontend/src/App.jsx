const LOADING_MESSAGES = [
  "Initializing AI Pipeline...",
  "Analyzing Feature Distributions...",
  "Identifying Bias Patterns...",
  "Optimizing Fairness Constraints...",
  "Applying Mitigation Algorithms...",
  "Generating Compliance Reports...",
  "Finalizing Decision Dashboard...",
  "Preparing Insight Visualizations..."
];

function formatApiError(err, fallbackMessage) {
  if (err?.code === "ECONNABORTED") {
    return "The request timed out. The backend may be overloaded or stuck — check its terminal for errors and try again.";
  }
  if (err?.request && !err?.response) {
    return "Cannot reach the backend. Make sure it is running (./run-backend.sh) and restart the frontend so it picks up the backend port.";
  }
  // The dev-server proxy answers with a bare 5xx (no "detail") when the backend is down.
  if (err?.response?.status >= 500 && typeof err?.response?.data?.detail !== "string") {
    return "The frontend server could not reach the backend. Make sure it is running (./run-backend.sh), then restart ./run-frontend.sh.";
  }
  const detail = err?.response?.data?.detail;
  const message = typeof detail === "string" ? detail : "";

  if (message.includes("Encoders require their input argument must be uniformly strings or numbers")) {
    return "Data preprocessing failed because one or more columns contain mixed value types. Please normalize those columns in the CSV and try again.";
  }

  return message || fallbackMessage;
}

function App() {
  // Number of completed steps (0 = nothing done yet, 4 = dashboard shown).
  const [step, setStep] = useState(0);
  const [file, setFile] = useState(null);
  const [uploadData, setUploadData] = useState(null);
  const [contract, setContract] = useState(null);
  const [targetColumn, setTargetColumn] = useState("");
  const [selectedBias, setSelectedBias] = useState([]);
  const [results, setResults] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [running, setRunning] = useState(false);
  const [loadingMsg, setLoadingMsg] = useState(LOADING_MESSAGES[0]);
  // Step-by-step status shown in the overlay during uploads.
  const [progressMsg, setProgressMsg] = useState("");
  const [uploadNote, setUploadNote] = useState("");
  const [availableResources, setAvailableResources] = useState(8);

  // Continuously change loading text while the pipeline runs
  useEffect(() => {
    let interval;
    if (running) {
      setLoadingMsg(LOADING_MESSAGES[0]);
      let index = 0;
      interval = setInterval(() => {
        index = (index + 1) % LOADING_MESSAGES.length;
        setLoadingMsg(LOADING_MESSAGES[index]);
      }, 2000);
    }
    return () => clearInterval(interval);
  }, [running]);

  const resetAll = () => {
    setUploadNote("");
    setStep(0);
    setFile(null);
    setUploadData(null);
    setContract(null);
    setTargetColumn("");
    setSelectedBias([]);
    setResults(null);
    setError("");
  };

  const selectableColumns = useMemo(() => {
    if (uploadData?.columns?.length) return uploadData.columns;
    return [];
  }, [uploadData]);

  const onUpload = async () => {
    if (!file) {
      setError("Please choose a CSV file.");
      return;
    }
    setLoading(true);
    setError("");
    setUploadData(null);
    setContract(null);
    setTargetColumn("");
    setSelectedBias([]);
    setResults(null);
    setStep(0);
    setUploadNote("");
    try {
      const { max_rows: maxRows } = await getLimits();
      const prepared = await prepareUpload(file, { maxRows, onPhase: setProgressMsg });

      setProgressMsg("Uploading… 0%");
      const data = await uploadFile(prepared.blob, prepared.filename, (pct) =>
        setProgressMsg(pct < 100 ? `Uploading… ${pct}%` : "Processing on server…")
      );
      setUploadData(data);
      setStep(1);

      const notes = [];
      if (prepared.sampled) {
        notes.push(
          `Large file: analysing a random sample of ${prepared.keptRows.toLocaleString()} of ` +
            `${prepared.totalRows.toLocaleString()} rows (record numbers refer to the sample).`
        );
      }
      if (data.excluded_id_columns?.length) {
        notes.push(`Identifier columns excluded from the analysis: ${data.excluded_id_columns.join(", ")}.`);
      }
      setUploadNote(notes.join(" "));

      // The backend suggests a two-valued column (e.g. "Survived", "isFraud").
      const defaultTarget = data.suggested_target || "";
      setTargetColumn(defaultTarget);

      if (!defaultTarget) {
        setError("No column has exactly two values, so there is no usable target. Bias analysis needs a yes/no style outcome column.");
      } else {
        try {
          setContract(await initContract(defaultTarget));
        } catch (err) {
          setError(formatApiError(err, "Could not use that column as target.") + " Pick a different target column.");
        }
      }
    } catch (err) {
      setError(formatApiError(err, "Upload failed."));
    } finally {
      setLoading(false);
      setProgressMsg("");
    }
  };

  const handleTargetChange = async (col) => {
    setTargetColumn(col);
    setError("");
    setResults(null);
    setContract(null);
    // Changing the target resets the bias selection on the backend too.
    setSelectedBias([]);
    setStep(1);
    if (!col) return;
    setLoading(true);
    try {
      setContract(await initContract(col));
    } catch (err) {
      setError(formatApiError(err, "Contract update failed."));
    } finally {
      setLoading(false);
    }
  };

  const handleBiasChange = async (biasCols) => {
    setSelectedBias(biasCols);
    setError("");
    setResults(null);
    setStep(biasCols.length ? 2 : 1);
    setLoading(true);
    try {
      const data = await selectBias(biasCols);
      setContract((prev) => ({ ...prev, ...data }));
    } catch (err) {
      setSelectedBias([]);
      setStep(1);
      setError(formatApiError(err, "Bias update failed."));
    } finally {
      setLoading(false);
    }
  };

  const onRunPipeline = async () => {
    setLoading(true);
    setRunning(true);
    setError("");
    const startTime = Date.now();
    try {
      const data = await runPipeline({ rowIndex: 0, availableResources });

      // Ensure at least 3s for the dynamic text to cycle
      const elapsed = Date.now() - startTime;
      if (elapsed < 3000) {
        await new Promise(r => setTimeout(r, 3000 - elapsed));
      }
      
      setResults(data);
      setStep(4);
    } catch (err) {
      setError(formatApiError(err, "Pipeline run failed."));
    } finally {
      setLoading(false);
      setRunning(false);
    }
  };

  const onScoreRecord = async (rowIndex) => {
    setLoading(true);
    setError("");
    try {
      const { decision, validation } = await scoreRecord({ rowIndex, availableResources });
      setResults((prev) => ({ ...prev, decision, validation }));
    } catch (err) {
      setError(formatApiError(err, "Scoring the record failed."));
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="page">
      <header className="topbar">
        <div className="brand">Bias Platform</div>
        <nav className="topnav">
          <a href="#home">Home</a>
          <a href="#pipeline">Pipeline</a>
          <a href="#results">Results</a>
        </nav>
        <button className="btn-new-run" onClick={resetAll}>New Run</button>
      </header>

      <main className="container" id="home">
        <section className="hero">
          <div className="floating-shape shape-1"></div>
          <div className="floating-shape shape-2"></div>
          <div className="floating-shape shape-3"></div>
          <div className="floating-shape shape-4"></div>
          <h1>Decision Intelligence Dashboard</h1>
          <p className="lead">
            Upload data, run fairness-aware inference, and inspect decision, validation, and monitoring outputs.
          </p>
        </section>

        <section id="pipeline">
          <h2>Pipeline Progress</h2>
          <div className="stepper-wrapper">
            <div className="stepper">
              {steps.map((s, idx) => (
                <div key={s.label} className={`step ${step > idx ? "active" : ""}`}>
                  <div className="step-header">
                    <div className="step-icon">{s.icon}</div>
                    <div className="step-number">{idx + 1}</div>
                  </div>
                  <p className="step-title">{s.label}</p>
                  <div className="step-desc-wrapper">
                    <div className="step-desc">{s.desc}</div>
                  </div>
                </div>
              ))}
            </div>
            <div className="timeline-wave-container">
              <div 
                className="timeline-wave-fill" 
                style={{ width: `${(step / steps.length) * 100}%` }}
              ></div>
            </div>
          </div>
        </section>

        <UploadPanel file={file} loading={loading} onFileChange={setFile} onUpload={onUpload} />
        {uploadNote && <p className="muted">{uploadNote}</p>}

        {uploadData && (
          <ColumnSelector
            columns={selectableColumns}
            binaryColumns={uploadData?.binary_columns || []}
            targetColumn={targetColumn}
            selectedBias={selectedBias}
            loading={loading}
            onTargetChange={handleTargetChange}
            onBiasChange={handleBiasChange}
          />
        )}

        {contract && (
          <PipelineRunner
            loading={loading}
            hasResults={Boolean(results)}
            canRun={selectedBias.length > 0}
            availableResources={availableResources}
            onResourcesChange={setAvailableResources}
            onRunPipeline={onRunPipeline}
          />
        )}

        {results && <ResultsDashboard results={results} loading={loading} onScoreRecord={onScoreRecord} />}

        {error && <p className="error">{error}</p>}
      </main>

      {loading && (
        <div className="loading-overlay">
          <div className="spinner-container">
            <div className="modern-spinner">
              <div className="neural-node"></div>
              <div className="neural-node"></div>
              <div className="neural-node"></div>
            </div>
            <p className="loading-text">{running ? loadingMsg : progressMsg || "Working..."}</p>
          </div>
        </div>
      )}

      <footer className="footer">
        <div className="footer-bottom">
          <p>&copy; {new Date().getFullYear()} Bias Platform</p>
        </div>
      </footer>
    </div>
  );
}

export default App;